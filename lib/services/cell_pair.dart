// Ни одного импорта — как у `trip_aggregates.dart`. Правило одно, и звонят
// его трое: живой писатель снапшотов, синтез снапшотов фоновой поездки и
// агрегат `trips.max_cell_spread_mv`. До этого патча правило существовало
// в ОДНОМ из трёх (геттер `halCellSpreadMv`, +131) и охраняло там только
// разброс — минимум и максимум писались непроверенной парой рядом с ним.
//
// ЧТО ПОКАЗАЛО ПОЛЕ 04.08. Фоновая поездка #155 несла 19 снапшотов, пять с
// ОТРИЦАТЕЛЬНЫМ разбросом (до −68 мВ) и агрегат 190 мВ при живой поездке
// того же дня в 4…9 мВ. Разбор экспорта:
//
//   * `cell_v_lowest` и `cell_v_highest` придушены в журнале по 10 с
//     КАЖДЫЙ и идут В ПРОТИВОФАЗЕ: медиана расстояния до парной строки
//     3 с, в пределах 1 с только 19 пар из 113;
//   * сами значения движутся с медианой 3.2 мВ/с и p90 11 мВ/с.
//
// Три секунды рассинхрона при 11 мВ/с дают порядка 33 мВ выдуманной
// разности — что и наблюдалось. Отсюда вывод, который стоил проверки
// зеркалом: выдуманы ВСЕ 19 разбросов, а не пять. Отрицательные — лишь те,
// где ошибка перевалила знак; остальные четырнадцать той же природы и
// просто легли положительными.
//
// ПОЧЕМУ ОКНА РАЗНЫЕ. Живой путь читает поток напрямую, там оба сигнала
// обновляются на ~48 Гц, и «пара внутри трёх секунд» на деле означает
// «внутри миллисекунд» — окно +131 верное, его не трогаем. В журнале
// придушивание до 10 с эту одномоментность уничтожает В ИСТОЧНИКЕ, и
// никакое правило поверх её не вернёт: там окно обязано быть жёстким.
// Источник починен встречной записью пары (см. HalOut.kt), после чего
// журнальные пары становятся одномоментными сами, и это же окно начинает
// пропускать их все. Дня переключения нет: на старых строках правило
// молчит, на парных пропускает.
//
// Замер по окнам на реальной #155 (зеркало `tools/mirror_plus193_cells.py`):
//
//   окно     тройки   отрицательных   агрегат
//   нет        19          5           190.0 мВ
//   3 с        12          3           190.0 мВ
//   1 с         6          0             9.0 мВ   ← совпадает с живой
//   0 с         1          0             7.0 мВ
//
// Только одна секунда даёт числа, сходящиеся с живой поездкой.

/// Согласованная тройка: минимум, максимум и их разность, всё в мВ.
typedef CellTriple = ({double minMv, double maxMv, double spreadMv});

/// Живой поток: оба сигнала на ~48 Гц. Константа +131, поведение
/// сохранено бит-в-бит.
const int kCellPairWindowLiveMs = 3000;

/// Журнал: сигналы придушены по 10 с и идут в противофазе. Окно жёсткое,
/// потому что здесь секунда рассинхрона — это секунда настоящего дрейфа
/// напряжений, а не задержка доставки.
const int kCellPairWindowJournalMs = 1000;

/// Тройка ячеек или `null`, если одномоментной пары нет.
///
/// Отказ ровно в четырёх случаях, и каждый значит «согласованной пары не
/// существует», а не «значение равно нулю»:
///   1. любое из двух значений отсутствует;
///   2. неизвестно время обновления любого из двух;
///   3. значения обновлялись дальше `windowMs` друг от друга;
///   4. максимум оказался ниже минимума — пара пришла из разных мгновений,
///      и это видно по знаку.
///
/// Возвращается тройка ЦЕЛИКОМ либо ничего: минимум и максимум из разных
/// мгновений так же ложны, как их разность, и записывать их по отдельности
/// значит сохранить ту же ошибку, спрятав её признак.
CellTriple? cellTriple({
  required double? loVolts,
  required int? loAtMs,
  required double? hiVolts,
  required int? hiAtMs,
  required int windowMs,
}) {
  if (loVolts == null || hiVolts == null) return null;
  if (loAtMs == null || hiAtMs == null) return null;
  if ((hiAtMs - loAtMs).abs() > windowMs) return null;
  final spread = (hiVolts - loVolts) * 1000.0;
  if (spread < 0) return null;
  return (
    minMv: loVolts * 1000.0,
    maxMv: hiVolts * 1000.0,
    spreadMv: spread,
  );
}

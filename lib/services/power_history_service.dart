// v0.1.94+193 — ИСТОРИЯ МОЩНОСТИ ПЕРЕЖИВАЕТ УХОД С ЭКРАНА.
//
// ЧТО БЫЛО. Кольцо на 120 отсчётов и таймер на 500 мс жили ВНУТРИ состояния
// карточки, и в двух копиях: `_PowerCardState` на широком ГУ и
// `_PowerCardTallState` на вертикальном. Следствие простое и заметное:
// уходишь с экрана «Вождение» — состояние карточки уничтожается, история
// обнуляется, возвращаешься к пустому графику. Окно было 60 с при любой
// ширине экрана, то есть 2175 логических точек показывали ту же минуту,
// что и 720.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ СЕРВИС, А НЕ ОДИН ИЗ ДВУХ СУЩЕСТВУЮЩИХ. Значение
// мощности берётся выражением `hal.useHalForPower ? hal.halPowerKw :
// svc.instantPowerKw`, то есть из ОБОИХ сервисов сразу. Положить буфер в
// любой из них значит заставить его знать про другой, а инвариант AA2 это
// запрещает прямо (`connection.dart` обязан оставаться HAL-free, и гейт
// проверяет это буквально по подстроке). Третий, знающий обоих, буквой AA2
// не запрещён — запрещено взаимное знание двух.
//
// НО ЗНАТЬ ОБОИХ ЕМУ И НЕ НУЖНО. Сервис не импортирует ни один из них:
// он получает КОЛБЭК, ровно тем же идиомом, что `dongleConnected` и
// `currentTripId` у HAL-сервиса и `halOwnsTripCheck` у OBD2. Выражение
// выбора источника остаётся там, где стояло, и новых связей не возникает
// вообще — ни одной строки с именем чужого сервиса.
//
// ТАЙМЕР ТИКАЕТ ВСЕГДА, а не только когда на экран кто-то смотрит. Иначе
// буфер снова обнулялся бы при уходе — то есть лечили бы болезнь и
// оставляли её же. Владелец сервиса один, живёт выше навигатора, и умирает
// вместе с приложением.
//
// МАСШТАБЫ ОСЕЙ ПЕРЕЕХАЛИ ВМЕСТЕ С КОЛЬЦОМ, и это не попутная уборка.
// Они считаются с сглаживанием ОТ ТИКА (0.15 на такт), то есть являются
// функцией буфера и числа тиков. Оставь их на экране — при возвращении
// шкала снова поехала бы от пола, и владелец увидел бы, как график, уже
// имея историю, полминуты подбирает масштаб. Это та же болезнь, только
// незаметнее.
//
// ЧАСТОТА 1 Гц, утверждено владельцем. По замерам +185 `pack_current`
// приходит с медианным интервалом 1.0 с, `motor_power` около 2 с — второй
// опрос в секунду записывал бы то же удержанное значение второй раз.
// РАЗМЕР КОЛЬЦА ПРОВЕРЕН АРИФМЕТИКОЙ, А НЕ НА ГЛАЗ. Первая редакция взяла
// 512 «с запасом», и зеркало `tools/mirror_plus193_slots.py` тут же показало
// цену такого запаса: на 2175 dp при dpr 0.875 полоса просит 951 слот, на
// 720 dp при 1.5 — до 540, и зажим упирался на ВСЕХ трёх экранах. А когда
// зажим упирается, шаг перестаёт быть двумя пикселями — то есть свойство,
// ради которого снят прежний зажим ширины, разрушается молча, и график
// выцветает вместо того, чтобы стать подробнее. 1024 отсчёта при одном в
// секунду — это 17 минут и восемь килобайт; ни то, ни другое не жмёт.

import 'dart:async';

import 'package:flutter/foundation.dart';

/// Кольцо мгновенной мощности, общее для всех экранов.
///
/// Значение приходит колбэком: `> 0` разряд, `< 0` рекуперация, `null` —
/// оба источника молчат. `null` сохраняется как есть и рисуется пропуском
/// столбика: перенос вперёд здесь был бы ложью о том, что данные шли.
class PowerHistoryService extends ChangeNotifier {
  /// Сколько отсчётов держим. При 1 Гц это 1024 секунды.
  ///
  /// Число выбрано ПО ЗАМЕРУ, а не с запасом на глаз: самая широкая наша
  /// полоса (2175 dp, dpr 0.875) просит 951 слот, и кольцо обязано быть
  /// заведомо больше — иначе зажим в `powerSlotsFor` начинает срабатывать, а
  /// вместе с ним пропадает целый шаг в два пикселя.
  static const int ringLength = 1024;

  /// Такт опроса. Смена этого числа меняет и длину окна каждого экрана —
  /// окно считается как «слотов × такт», и подпись под графиком берётся
  /// оттуда же, а не из литерала.
  static const Duration tick = Duration(seconds: 1);

  // Масштабы половин оси. Числа и смысл — из +70 («вариант B» владельца):
  // фиксированная шкала ±200/100 кВт превращала городскую езду в прямую.
  static const double dischargeFloorKw = 10.0;
  static const double dischargeCeilKw = 200.0; // подтверждённый пик ~223
  static const double regenFloorKw = 10.0;
  static const double regenCeilKw = 100.0;
  static const double _scaleEase = 0.15; // подход к цели за такт

  /// Сколько ПОСЛЕДНИХ отсчётов видит экран. Обновляется в [tail]: длину
  /// окна знает только экран, потому что задаёт её его ширина.
  ///
  /// ЗАЧЕМ ЭТО ПОЛЕ. Масштаб осей обязан следить за максимумом ВИДИМОГО, а
  /// не всего накопленного. Первая редакция считала по всему кольцу, и это
  /// был возврат болезни, которую лечил +70: при кольце на 1024 отсчёта
  /// один разгон в 150 кВт прижимал бы шкалу почти на четверть часа, и
  /// городская езда снова стала бы прямой линией. Раньше это не бросалось в
  /// глаза только потому, что кольцо было ровно окном — 120 отсчётов по
  /// 500 мс, те же 60 секунд.
  int _windowHint = _defaultWindow;

  /// Пока экран ни о чём не просил, шкала ведёт себя как до +193: минута.
  static const int _defaultWindow = 60;

  final double? Function() _read;
  final List<double?> _hist =
      List<double?>.filled(ringLength, null, growable: false);
  int _head = 0;
  int _filled = 0;
  Timer? _timer;

  double _dischargeScale = dischargeFloorKw;
  double _regenScale = regenFloorKw;

  PowerHistoryService({required double? Function() read}) : _read = read {
    _timer = Timer.periodic(tick, (_) => _sample());
  }

  double get dischargeScale => _dischargeScale;
  double get regenScale => _regenScale;

  /// Последние [n] отсчётов, старейший первым — в том виде, в котором их
  /// ждёт художник. Длину просит ЭКРАН, потому что задаёт её его ширина;
  /// сервис про экраны не знает и знать не должен.
  ///
  /// ВОЗВРАЩАЕТСЯ РОВНО [n] ЭЛЕМЕНТОВ, и это не мелочь. Художник считает шаг
  /// как «ширина ÷ число отсчётов», поэтому вернуть меньше значило бы менять
  /// шаг по мере наполнения истории: первые полминуты после запуска столбики
  /// расползались бы по всей полосе и потом сжимались на глазах водителя.
  /// Недостающее начало заполняется пустотами — новое всегда справа, история
  /// растёт налево, шаг постоянен с первой секунды.
  ///
  /// Пустой сервис отдаёт список из одних пустот: на экране это «нет
  /// истории», а не «нет экрана» — художник рисует нулевую линию и выходит.
  List<double?> tail(int n) {
    if (n <= 0) return const <double?>[];
    // Окно масштаба равно окну показа. Просит экран — значит он же и
    // сообщает, что именно видно.
    _windowHint = n > ringLength ? ringLength : n;
    final out = List<double?>.filled(n, null, growable: false);
    final take = n < _filled ? n : _filled;
    for (var i = 0; i < take; i++) {
      // _head — позиция СЛЕДУЮЩЕЙ записи, значит последний отсчёт лежит на
      // _head-1. Идём от него назад и заполняем результат с конца.
      final idx = (_head - 1 - i) % ringLength;
      out[n - 1 - i] = _hist[idx < 0 ? idx + ringLength : idx];
    }
    return out;
  }

  void _sample() {
    double? p;
    try {
      p = _read();
    } catch (_) {
      // Источник мощности не имеет права уронить общий таймер: остальные
      // экраны и накопление не при чём. Пропуск отсчёта равен пропуску
      // столбика, что и означает «данных в этот момент не было».
      p = null;
    }
    _hist[_head] = p;
    _head = (_head + 1) % ringLength;
    if (_filled < ringLength) _filled++;
    _recomputeScales();
    notifyListeners();
  }

  /// Обе половины шкалы подводятся к (максимум окна × 1.2) с зажимом в
  /// пол и потолок, независимо друг от друга: долгий накат не должен
  /// сжимать ось разряда, и наоборот.
  void _recomputeScales() {
    double maxDis = 0, maxReg = 0;
    // Только видимое окно, а не всё кольцо — см. [_windowHint].
    final look = _windowHint < _filled ? _windowHint : _filled;
    for (var i = 0; i < look; i++) {
      final idx = (_head - 1 - i) % ringLength;
      final s = _hist[idx < 0 ? idx + ringLength : idx];
      if (s == null) continue;
      if (s > maxDis) maxDis = s;
      if (-s > maxReg) maxReg = -s;
    }
    final disTarget = (maxDis * 1.2).clamp(dischargeFloorKw, dischargeCeilKw);
    final regTarget = (maxReg * 1.2).clamp(regenFloorKw, regenCeilKw);
    _dischargeScale += (disTarget - _dischargeScale) * _scaleEase;
    _regenScale += (regTarget - _regenScale) * _scaleEase;
  }

  @override
  void dispose() {
    _timer?.cancel();
    _timer = null;
    super.dispose();
  }
}

/// Сколько столбиков влезает в полосу заданной ширины.
///
/// ДВА ФИЗИЧЕСКИХ ПИКСЕЛЯ НА СЛОТ: один под столбик, один под зазор. Шаг
/// обязан быть целым в пикселях — иначе сглаживание размазывает
/// однопиксельный столбик по двум соседним, каждый в половину яркости, и
/// график выцветает вместо того, чтобы стать плотнее.
///
/// Отсюда же снят прежний нижний зажим ширины столбика: он и был
/// блокировщиком. При шаге 1.33 dp (720 dp, dpr 1.5) зажим требовал
/// минимум 1.5 dp, то есть столбик шире шага, и столбики налезали друг на
/// друга. Со счётом от пикселей шаг ровно два пикселя ВСЕГДА, поэтому
/// зажимать нечего.
///
/// Нижняя граница на число слотов нужна не для красоты: при нулевой или
/// неограниченной ширине `floor` даёт ноль, а ноль слотов — это деление на
/// ноль в художнике.
int powerSlotsFor(double widthDp, double devicePixelRatio) {
  final px = widthDp * devicePixelRatio;
  final slots = (px / 2).floor();
  if (slots < 24) return 24;
  if (slots > PowerHistoryService.ringLength) {
    return PowerHistoryService.ringLength;
  }
  return slots;
}

/// Ширина столбика в логических точках: ровно один физический пиксель.
double powerBarWidthFor(double devicePixelRatio) {
  final dpr = devicePixelRatio <= 0 ? 1.0 : devicePixelRatio;
  return 1.0 / dpr;
}
